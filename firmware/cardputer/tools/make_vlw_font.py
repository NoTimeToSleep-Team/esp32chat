"""Generate a VLW bitmap font (ASCII + Cyrillic) from a TTF for M5GFX.

Produces a C header with a byte array that can be passed to
M5Cardputer.Display.loadFont(array) (VLW is the default font type).

Usage:
    python tools/make_vlw_font.py [--ttf TTF] [--size N] [--out HEADER] [--threshold 128]

Defaults: C:/Windows/Fonts/tahoma.ttf, size 10, src/lc_font_10.h
"""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

from PIL import ImageFont

RANGES = [
    (0x20, 0x7E),    # ASCII printable
    (0x400, 0x45F),  # Cyrillic
    (0x401, 0x401),  # Yo
    (0x451, 0x451),  # yo
    (0x2013, 0x2014),  # dashes
    (0x2018, 0x201D),  # quotes
    (0x2026, 0x2026),  # ellipsis
    (0x2190, 0x2193),  # arrows
]


def build_chars() -> list[int]:
    codepoints: set[int] = set()
    for start, end in RANGES:
        codepoints.update(range(start, end + 1))
    return sorted(codepoints)


def render_glyphs(ttf: str, size: int, threshold: int):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()

    glyphs = []
    for cp in build_chars():
        ch = chr(cp)
        try:
            mask = font.getmask(ch, mode="L")
        except Exception:
            continue
        w, h = mask.size
        bbox = font.getbbox(ch)
        left = int(bbox[0])
        top = int(bbox[1])
        advance = int(round(font.getlength(ch)))

        bitmap = bytearray(mask) if w and h else bytearray()
        if threshold > 0:
            bitmap = bytearray(255 if b >= threshold else 0 for b in bitmap)

        d_y = ascent - top
        glyphs.append(
            {
                "cp": cp,
                "w": w,
                "h": h,
                "advance": advance,
                "dy": d_y,
                "dx": left,
                "bitmap": bytes(bitmap),
            }
        )
    return glyphs, ascent, descent


def build_vlw(glyphs, ascent: int, descent: int, size: int) -> bytes:
    data = struct.pack(">6I", len(glyphs), 0, size, 0, ascent, descent)
    for g in glyphs:
        data += struct.pack(
            ">7I",
            g["cp"],
            g["h"],
            g["w"],
            g["advance"] & 0xFFFFFFFF,
            g["dy"] & 0xFFFF,
            g["dx"] & 0xFF,
            0,
        )
    for g in glyphs:
        data += g["bitmap"]
    return data


def write_header(data: bytes, out_path: Path, name: str) -> None:
    lines = [
        "// Generated by tools/make_vlw_font.py - do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"const uint8_t {name}[] = {{",
    ]
    row = []
    for i, b in enumerate(data):
        row.append(f"{b}")
        if len(row) == 16:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines.append("};")
    lines.append(f"const unsigned int {name}_len = {len(data)};")
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ttf", default="C:/Windows/Fonts/tahoma.ttf")
    parser.add_argument("--size", type=int, default=10)
    parser.add_argument("--out", default="")
    parser.add_argument("--threshold", type=int, default=128)
    parser.add_argument("--name", default="")
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]
    out_path = Path(args.out) if args.out else root / "src" / f"lc_font_{args.size}.h"
    name = args.name or f"lc_font_{args.size}"

    glyphs, ascent, descent = render_glyphs(args.ttf, args.size, args.threshold)
    data = build_vlw(glyphs, ascent, descent, args.size)
    write_header(data, out_path, name)
    print(
        f"font: {args.ttf} size={args.size} glyphs={len(glyphs)} "
        f"ascent={ascent} descent={descent} bytes={len(data)}"
    )
    print("written:", out_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
